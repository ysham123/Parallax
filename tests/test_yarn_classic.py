LOCK = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"


def find_yarn():
    candidate = os.environ.get("PARALLAX_TEST_YARN") or shutil.which("yarn")
    if not candidate:
        return None
    try:
        yarn_classic_tool(str(Path(candidate).absolute()))
    except ValueError:
        return None
    return str(Path(candidate).absolute())


YARN = find_yarn()


class YarnInputTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        monorepo(self.root)

    def test_fingerprint_covers_lock_root_and_every_member_manifest(self):
        inputs = yarn_classic_inputs(self.root)
        self.assertEqual(set(inputs), {"package.json", "yarn.lock", "packages/app/package.json", "packages/util/package.json"})
        (self.root / "packages/util/package.json").write_text(json.dumps({"name": "@fx/util", "version": "1.0.1", "main": "index.js"}))
        self.assertNotEqual(yarn_classic_inputs(self.root), inputs)

    def test_berry_pnpm_and_unsafe_dependency_sources_are_refused(self):
        cases = [
            lambda: (self.root / ".yarnrc.yml").write_text("nodeLinker: pnp\n"),
            lambda: (self.root / "pnpm-lock.yaml").write_text("lockfileVersion: 6\n"),
            lambda: (self.root / "yarn.lock").write_text("__metadata:\n  version: 6\n"),
            lambda: write(self.root / "packages/app/package.json", {"name": "@fx/app", "dependencies": {"x": "file:../../outside"}}),
            lambda: write(self.root / "packages/app/package.json", {"name": "@fx/app", "dependencies": {"x": "git+ssh://host/repo"}}),
            lambda: write(self.root / "package.json", {"name": "root", "private": True, "workspaces": ["../escape"]}),
            lambda: write(self.root / "package.json", {"name": "root", "private": False, "workspaces": ["packages/*"]}),
            lambda: write(self.root / "package.json", {"name": "root", "private": True, "packageManager": "yarn@4.0.0", "workspaces": ["packages/*"]}),
            lambda: (self.root / "yarn.lock").write_text(LOCK + 'x@1:\n  resolved "http://insecure.example/x.tgz"\n'),
        ]
        for index, mutate in enumerate(cases):
            with self.subTest(index=index):
                shutil.rmtree(self.root); self.root.mkdir(); monorepo(self.root)
                mutate()
                with self.assertRaises(ValueError):
                    yarn_classic_inputs(self.root)

    def test_symlinked_members_and_nested_workspaces_are_refused(self):
        outside = Path(tempfile.mkdtemp()); self.addCleanup(shutil.rmtree, outside)
        write(outside / "package.json", {"name": "@fx/outside"})
        (self.root / "packages/linked").symlink_to(outside, target_is_directory=True)
        with self.assertRaises(ValueError):
            yarn_classic_inputs(self.root)
        (self.root / "packages/linked").unlink()
        write(self.root / "packages/util/package.json", {"name": "@fx/util", "workspaces": ["nested/*"]})
        with self.assertRaises(ValueError):
            yarn_classic_inputs(self.root)

    def test_tool_must_be_a_classic_package_launcher(self):
        fake = self.root / "tool/bin/yarn.js"; fake.parent.mkdir(parents=True); fake.write_text("// fake\n")
        (self.root / "tool/lib").mkdir(); (self.root / "tool/lib/cli.js").write_text("// fake\n")
        write(self.root / "tool/package.json", {"name": "yarn", "version": "4.1.0"})
        with self.assertRaises(ValueError):
            yarn_classic_tool(str(fake))
        write(self.root / "tool/package.json", {"name": "yarn", "version": "1.22.22"})
        self.assertEqual(yarn_classic_tool(str(fake))["version"], "1.22.22")
        with self.assertRaises(ValueError):
            yarn_classic_tool(str(self.root / "tool/lib/cli.js"))


class YarnAssessmentTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        git(self.root, "init", "-q")
        monorepo(self.root)
        write(self.root / "packages/app/package.json", {"name": "@fx/app", "version": "1.0.0", "scripts": {"test": "node test.js"}})

    def assess(self, yarn):
        from parallax.assessment import assess_project
        with patch("parallax.provisioning.shutil.which", return_value=yarn):
            return assess_project(self.root, roots=["packages/app"])

    @unittest.skipUnless(YARN, "requires Yarn Classic 1.22.x (set PARALLAX_TEST_YARN)")
    def test_members_report_root_install_and_yarn_checks(self):
        result = self.assess(YARN)
        package = next(p for p in result.packages if p["root"] == "packages/app")
        self.assertEqual(package["manager"], "yarn")
        self.assertIn("Yarn Classic frozen-lock", package["setup"])
        self.assertIn(["yarn", "run", "test"], [c.argv for c in result.proposed_checks])
        self.assertFalse([i for i in result.issues if i["severity"] == "blocker"], result.issues)

    def test_missing_tool_and_unsafe_inputs_are_blockers(self):
        result = self.assess(None)
        self.assertTrue(any("Yarn Classic" in i["message"] for i in result.issues if i["severity"] == "blocker"), result.issues)
        (self.root / ".yarnrc.yml").write_text("nodeLinker: pnp\n")
        result = self.assess(YARN or "/missing/yarn")
        self.assertEqual(result.status, "blocked")


@unittest.skipUnless(YARN and shutil.which("node"), "requires Node and Yarn Classic 1.22.x (set PARALLAX_TEST_YARN)")
class YarnEngineTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name); self.project = self.root / "project"; self.project.mkdir()
        git(self.project, "init", "-q"); git(self.project, "config", "user.name", "Test"); git(self.project, "config", "user.email", "test@example.com")
        monorepo(self.project)
        git(self.project, "add", "."); git(self.project, "commit", "-qm", "monorepo")
        self.store = Store(self.root / "state")
        self.checks = [CheckSpec(name="app", argv=[YARN, "run", "test"], cwd="packages/app"),
                       CheckSpec(name="util", argv=[YARN, "run", "test"], cwd="packages/util")]

    def seed(self, checks):
        spec = RunSpec(workspace=str(self.project), prompt="Check", team=[Participant(provider="claude"), Participant(provider="grok", role="reviewer")], checks=checks)
        run_id = str(uuid.uuid4())
        result = RunResult(run_id=run_id, status="interrupted", spec=spec).model_dump()
        result["artifacts"] = {"directory": str(self.store.home / "runs" / run_id), "started_at": time.time(), "user_checks": [c.model_dump() for c in checks]}
        self.store.save(result)
        manager = WorkspaceManager(self.project, Path(result["artifacts"]["directory"]))
        manager.prepare()
        engine = Engine(self.store, FakeRegistry()); engine.cancel_flags[run_id] = asyncio.Event()
        return run_id, manager, engine

    async def test_workspace_members_see_hoisted_packages_with_one_private_install(self):
        run_id, manager, engine = self.seed(self.checks)
        original = (self.project / ".git" / "index").read_bytes()
        calls = []
        command = engine._command
        async def counted(*args, **kwargs):
            calls.append(args[1]); return await command(*args, **kwargs)
        with patch.object(engine, "_command", new=counted):
            evidence = await asyncio.wait_for(engine._checks(run_id, manager.integration_path, self.checks), 120)
        self.assertTrue(all(item["ok"] for item in evidence), evidence)
        self.assertIn("util says 7", evidence[0]["output"])
        installs = [argv for argv in calls if "install" in argv]
        self.assertEqual(len(installs), 1, installs)
        self.assertIn("--frozen-lockfile", installs[0]); self.assertIn("--ignore-scripts", installs[0]); self.assertIn("--no-default-rc", installs[0])
        self.assertTrue(any(Path(self.store.get(run_id)["artifacts"]["directory"]).glob("environments/*/yarn-cache")))
        self.assertFalse((self.project / "node_modules").exists())
        self.assertEqual((self.project / ".git" / "index").read_bytes(), original)

    async def test_lifecycle_scripts_and_rc_redirection_do_not_run(self):
        canary = self.root / "canary"
        write(self.project / "package.json", {"name": "root", "private": True, "workspaces": ["packages/*"],
              "scripts": {"postinstall": f"node -e \"require('fs').writeFileSync({json.dumps(str(canary))},'ran')\""}})
        (self.project / ".yarnrc").write_text('yarn-path "./evil.js"\n')
        (self.project / "evil.js").write_text(f"require('fs').writeFileSync({json.dumps(str(canary))},'redirected')\n")
        git(self.project, "add", "."); git(self.project, "commit", "-qm", "canaries")
        run_id, manager, engine = self.seed(self.checks)
        evidence = await asyncio.wait_for(engine._checks(run_id, manager.integration_path, self.checks), 120)
        self.assertTrue(all(item["ok"] for item in evidence), evidence)
        self.assertFalse(canary.exists())

    async def test_invalid_tool_at_check_time_is_recorded_as_unavailable(self):
        run_id, manager, engine = self.seed(self.checks)
        await asyncio.wait_for(engine._checks(run_id, manager.integration_path, self.checks), 120)
        with patch("parallax.provisioning.yarn_classic_tool", side_effect=ValueError("Yarn changed")):
            with patch.object(engine, "_ensure_environment", new=AsyncMock(return_value=({}, None))):
                evidence = await asyncio.wait_for(engine._checks(run_id, manager.integration_path, self.checks), 60)
        self.assertTrue(all(item["error"] == "check_unavailable" and not item["ok"] for item in evidence), evidence)

    async def test_untracked_ignore_rule_blocks_install_before_any_command(self):
        (self.project / ".gitignore").write_text("dist/\n")
        git(self.project, "add", "."); git(self.project, "commit", "-qm", "no ignore")
        run_id, manager, engine = self.seed(self.checks)
        with patch.object(engine, "_command", new=AsyncMock()) as command:
            with self.assertRaisesRegex(ValueError, "gitignored"):
                await engine._checks(run_id, manager.integration_path, self.checks)
        command.assert_not_called()


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value))


def monorepo(root):
    write(root / "package.json", {"name": "root", "private": True, "workspaces": ["packages/*"]})
    (root / "yarn.lock").write_text(LOCK)
    (root / ".gitignore").write_text("node_modules/\n")
    write(root / "packages/util/package.json", {"name": "@fx/util", "version": "1.0.0", "main": "index.js", "scripts": {"test": "node -e \"require('./index.js')\""}})
    (root / "packages/util/index.js").write_text("module.exports = 7;\n")
    write(root / "packages/app/package.json", {"name": "@fx/app", "version": "1.0.0", "dependencies": {"@fx/util": "1.0.0"}, "scripts": {"test": "node test.js"}})
    (root / "packages/app/test.js").write_text("const value = require('@fx/util');\nrequire('assert').strictEqual(value, 7);\nconsole.log('util says ' + value);\n")


if __name__ == "__main__":
    unittest.main()
